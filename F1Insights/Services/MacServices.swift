import Foundation
import SwiftUI
#if os(macOS)
import AppKit
#elseif os(iOS)
import UIKit
#endif

/// Cross-platform services: Apple Maps integration, Pasteboard, Haptics, and Dock updates.
@MainActor
enum PlatformServices {

    // MARK: - URL Opening

    private static func open(_ url: URL?) {
        guard let url else { return }
        #if os(macOS)
        NSWorkspace.shared.open(url)
        #elseif os(iOS)
        UIApplication.shared.open(url)
        #endif
        performHapticFeedback()
    }

    // MARK: - Apple Maps Integration

    /// Opens the specified F1 circuit in Apple Maps with satellite imagery and track coordinates.
    static func openInAppleMaps(circuit: Circuit) {
        var components = URLComponents(string: "https://maps.apple.com/")
        if let latStr = circuit.location.lat, let lonStr = circuit.location.long,
           let lat = Double(latStr), let lon = Double(lonStr) {
            components?.queryItems = [
                URLQueryItem(name: "ll", value: "\(lat),\(lon)"),
                URLQueryItem(name: "q", value: circuit.circuitName),
                URLQueryItem(name: "t", value: "k")
            ]
        } else {
            let query = [circuit.circuitName, circuit.location.locality, circuit.location.country]
                .compactMap { $0 }
                .joined(separator: ", ")
            components?.queryItems = [
                URLQueryItem(name: "q", value: query),
                URLQueryItem(name: "t", value: "k")
            ]
        }
        open(components?.url)
    }

    // MARK: - Web & Wikipedia Integration

    /// Opens a Wikipedia or web search page in the user's default browser.
    static func openWikipedia(query: String) {
        let encoded = query.addingPercentEncoding(withAllowedCharacters: .urlQueryAllowed) ?? query
        open(URL(string: "https://en.wikipedia.org/wiki/Special:Search?search=\(encoded)"))
    }

    // MARK: - Pasteboard & Haptics

    /// Copies text to the system pasteboard and triggers a haptic pulse.
    static func copyToPasteboard(_ text: String) {
        #if os(macOS)
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(text, forType: .string)
        #elseif os(iOS)
        UIPasteboard.general.string = text
        #endif
        performHapticFeedback()
    }

    /// Performs subtle haptic feedback.
    static func performHapticFeedback() {
        #if os(macOS)
        NSHapticFeedbackManager.defaultPerformer.perform(.generic, performanceTime: .default)
        #elseif os(iOS)
        let generator = UIImpactFeedbackGenerator(style: .medium)
        generator.prepare()
        generator.impactOccurred()
        #endif
    }

    // MARK: - Dock Tile Live Updates (macOS only)

    /// Updates the macOS Dock tile badge with the next upcoming Grand Prix round if within 14 days.
    static func updateDockTile(with races: [Race]) {
        #if os(macOS)
        let now = Date()
        if let next = races.nextUpcoming(after: now),
           let date = next.startDate,
           let days = Calendar.current.dateComponents([.day], from: now, to: date).day,
           (0...14).contains(days) {
            NSApp.dockTile.badgeLabel = "R\(next.round)"
        } else {
            NSApp.dockTile.badgeLabel = nil
        }
        #endif
    }

    // MARK: - Export Formatters

    private static func formatMarkdownDocument(
        title: String,
        metadata: [String],
        headers: String,
        alignment: String,
        rows: [[String]]
    ) -> String {
        var lines = ["# \(title)"] + metadata + ["", headers, alignment]
        for row in rows {
            lines.append("| " + row.joined(separator: " | ") + " |")
        }
        lines.append("")
        lines.append("*Generated by F1 Insights*")
        return lines.joined(separator: "\n")
    }

    /// Formats race results as a GitHub Flavored Markdown table.
    static func generateMarkdownTable(race: Race, results: [RaceResult]) -> String {
        var metadata = ["Circuit: \(race.circuit.circuitName), \(race.circuit.location.country ?? "")"]
        if let d = race.startDate {
            metadata.append("Date: \(d.formatted(date: .abbreviated, time: .omitted))")
        }
        return formatMarkdownDocument(
            title: "\(race.raceName) - Round \(race.round) (\(race.season))",
            metadata: metadata,
            headers: "| Pos | No | Driver | Car | Laps | Time/Retired | Pts |",
            alignment: "|:---:|:---:|:---|:---|:---:|:---|:---:|",
            rows: results.map { r in
                [
                    r.positionText,
                    r.number ?? "—",
                    r.driver.fullName,
                    r.constructor.name,
                    r.laps ?? "—",
                    r.time?.time ?? r.status,
                    r.points
                ]
            }
        )
    }

    /// Formats qualifying results as Markdown.
    static func generateQualifyingMarkdown(race: Race, results: [QualifyingResult]) -> String {
        formatMarkdownDocument(
            title: "Qualifying - \(race.raceName) (\(race.season))",
            metadata: ["Circuit: \(race.circuit.circuitName)"],
            headers: "| Pos | No | Driver | Car | Q1 | Q2 | Q3 |",
            alignment: "|:---:|:---:|:---|:---|:---|:---|:---|",
            rows: results.map { r in
                [
                    r.position,
                    r.number ?? "—",
                    r.driver.fullName,
                    r.constructor.name,
                    r.q1 ?? "—",
                    r.q2 ?? "—",
                    r.q3 ?? "—"
                ]
            }
        )
    }

    /// Formats race results as CSV data.
    static func generateCSV(race: Race, results: [RaceResult]) -> String {
        let header = "Position,Number,Driver,Code,Team,Laps,TimeOrStatus,Points"
        let rows = results.map { r in
            [
                r.position,
                r.number ?? "",
                "\"\(r.driver.fullName)\"",
                r.driver.code ?? "",
                "\"\(r.constructor.name)\"",
                r.laps ?? "",
                "\"\(r.time?.time ?? r.status)\"",
                r.points
            ].joined(separator: ",")
        }
        return ([header] + rows).joined(separator: "\n")
    }
}

/// Backwards-compatibility typealias for MacServices
typealias MacServices = PlatformServices

